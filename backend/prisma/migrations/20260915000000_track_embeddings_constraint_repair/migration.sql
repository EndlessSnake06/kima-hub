-- Repair track_embeddings when it has lost its uniqueness and enforcement objects.
--
-- WHY THIS EXISTS. This table's primary key, foreign key and indexes have gone
-- missing on a real installation: a database rebuilt outside `prisma migrate
-- deploy` (or restored from a dump that dropped constraints) keeps every COLUMN
-- and silently loses every CONSTRAINT. Nothing in the application notices,
-- because the table still reads and writes as a plain table -- but the CLAP
-- analyzer's upsert
--
--     INSERT INTO track_embeddings (...) VALUES (...)
--     ON CONFLICT (track_id) DO UPDATE SET ...
--
-- hard-fails on every single track with
--
--     42P10: there is no unique or exclusion constraint matching the
--            ON CONFLICT specification
--
-- so no audio embedding is stored again, ever, and the vibe map quietly rots.
--
-- `prisma migrate deploy` cannot fix this by itself: the migrations that created
-- these objects (20260127000000_add_pgvector,
-- 20260128100000_reduce_embedding_dimension, 20260307000000_switch_ivfflat_to_hnsw)
-- are already recorded as applied, so they are skipped. Hence this migration,
-- which re-asserts them.
--
-- IDEMPOTENT BY CONSTRUCTION. Every step is guarded by a catalog lookup, so this
-- is safe against a table that has all, some or none of these objects, and it is
-- a no-op on a healthy database (the normal case for nearly every install).
--
-- Object names match the original DDL exactly -- track_embeddings_pkey,
-- track_embeddings_track_id_fkey, track_embeddings_embedding_idx,
-- track_embeddings_model_version_idx -- so `prisma migrate diff` stays clean and
-- Prisma does not report permanent drift.
--
-- NOTE ON INDEX LOCKS: the HNSW index is created without CONCURRENTLY because
-- Prisma runs each migration inside a transaction and CONCURRENTLY is not
-- permitted there. On a table of this size (tens of thousands of rows) the build
-- takes seconds. If this ever needs to run against a table large enough to
-- matter, split it into its own migration with --create-only and run it outside
-- the transaction.

DO $$
DECLARE
  removed integer;
BEGIN
  IF to_regclass('public.track_embeddings') IS NULL THEN
    -- Fresh database: the table is created later in the migration history, or
    -- never existed here. Nothing to repair.
    RAISE NOTICE '[repair] track_embeddings does not exist; nothing to do';
    RETURN;
  END IF;

  -- 1. Drop embeddings whose track is gone. The foreign key cannot be
  --    re-created while they are present, and they are unreachable derived
  --    data: a row here is a cached vector for a track, worthless without the
  --    track, and regenerated by the analyzer if the track returns.
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'track_embeddings_track_id_fkey'
  ) THEN
    DELETE FROM track_embeddings e
    WHERE NOT EXISTS (SELECT 1 FROM "Track" t WHERE t.id = e.track_id);
    GET DIAGNOSTICS removed = ROW_COUNT;
    IF removed > 0 THEN
      RAISE NOTICE '[repair] track_embeddings: removed % orphaned row(s) with no matching track', removed;
    END IF;
  END IF;

  -- 2. Collapse duplicate track_id rows, keeping the most recently analyzed
  --    (ctid breaks ties deterministically). A primary key cannot be added
  --    while duplicates exist. Same reasoning as step 1: the newest vector for
  --    a track is the one the analyzer's upsert would have left in place.
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    WHERE t.relname = 'track_embeddings' AND c.contype = 'p'
  ) THEN
    DELETE FROM track_embeddings e
    USING track_embeddings keep
    WHERE e.track_id = keep.track_id
      AND (e.analyzed_at, e.ctid) < (keep.analyzed_at, keep.ctid);
    GET DIAGNOSTICS removed = ROW_COUNT;
    IF removed > 0 THEN
      RAISE NOTICE '[repair] track_embeddings: removed % duplicate row(s), keeping the newest per track_id', removed;
    END IF;
  END IF;

  -- 3. Primary key. This is the object whose absence breaks every embedding
  --    write, because ON CONFLICT (track_id) needs it.
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    WHERE t.relname = 'track_embeddings' AND c.contype = 'p'
  ) THEN
    ALTER TABLE track_embeddings
      ADD CONSTRAINT track_embeddings_pkey PRIMARY KEY (track_id);
    RAISE NOTICE '[repair] track_embeddings: restored PRIMARY KEY (track_id)';
  END IF;

  -- 4. Foreign key with cascade delete, so deleting a track takes its
  --    embedding with it (the analyzer cannot do that itself).
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'track_embeddings_track_id_fkey'
  ) THEN
    ALTER TABLE track_embeddings
      ADD CONSTRAINT track_embeddings_track_id_fkey
      FOREIGN KEY (track_id) REFERENCES "Track"(id)
      ON UPDATE CASCADE ON DELETE CASCADE;
    RAISE NOTICE '[repair] track_embeddings: restored FOREIGN KEY -> "Track"(id) ON DELETE CASCADE';
  END IF;

  -- 5. Similarity index. Without it every vibe query degrades to a full scan
  --    over the whole embedding table.
  IF NOT EXISTS (
    SELECT 1 FROM pg_class WHERE relname = 'track_embeddings_embedding_idx'
  ) THEN
    CREATE INDEX "track_embeddings_embedding_idx" ON "track_embeddings"
      USING hnsw ("embedding" vector_cosine_ops) WITH (m = 16, ef_construction = 200);
    RAISE NOTICE '[repair] track_embeddings: restored HNSW index on embedding';
  END IF;

  -- 6. Model-version index, used to filter embeddings by model version.
  IF NOT EXISTS (
    SELECT 1 FROM pg_class WHERE relname = 'track_embeddings_model_version_idx'
  ) THEN
    CREATE INDEX "track_embeddings_model_version_idx"
      ON "track_embeddings" ("model_version");
    RAISE NOTICE '[repair] track_embeddings: restored index on model_version';
  END IF;
END $$;
